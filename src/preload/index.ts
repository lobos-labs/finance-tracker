// A refusal by the plan comes back as error 'plan' with the feature; the renderer reads it from the message (planLock in lib.ts).
type Envelope = { ok: true; data: unknown } | { ok: false; error: string; feature?: string }

async function call<T>(channel: string, ...args: unknown[]): Promise<T> {
  const res = (await ipcRenderer.invoke(channel, ...args)) as Envelope
  if (!res.ok) throw new Error(res.error === 'plan' && res.feature ? `plan:${res.feature}` : res.error)
  return res.data as T
}

function subscribe<T>(channel: string, cb: (payload: T) => void): () => void {
  const listener = (_e: IpcRendererEvent, payload: T): void => cb(payload)
  ipcRenderer.on(channel, listener)
  return () => ipcRenderer.removeListener(channel, listener)
}

